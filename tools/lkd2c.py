#!/usr/bin/env python3
"""
lkd2c.py - turns a Pioneer OEL animation (.lkd) into a C++ header for the
`pioneer` saver.

    python3 tools/lkd2c.py movie8_f.lkd dolphins -o components/after_dark/ad_art_pioneer_dolphins.h

An .lkd is a 20-byte header ("zLKD", version, two unknowns, frame count),
then a gzip of a tar holding one 24-bit BMP: the frames stacked top to
bottom. The format was worked out by carozerra
(https://github.com/youxufkhan/carozerra), which also keeps the clips.

Each clip has four shades. They are stored as levels 0-3, darkest first,
packed four pixels a byte with the leftmost in the top bits: the dithering
leaves too little for compression to win (zlib saves under a fifth), and
plain packing lets the saver read any pixel directly.
"""
import argparse
import gzip
import io
import struct
import tarfile


def frames(path):
    raw = open(path, 'rb').read()
    if raw[:4] != b'zLKD':
        raise SystemExit(f'{path}: not an .lkd')
    count = struct.unpack('<I', raw[16:20])[0]
    tar = tarfile.open(fileobj=io.BytesIO(gzip.decompress(raw[20:])))
    member = next(m for m in tar.getmembers() if m.isfile())
    bmp = tar.extractfile(member).read()
    if bmp[:2] != b'BM' or struct.unpack('<H', bmp[28:30])[0] != 24:
        raise SystemExit(f'{path}: expected a 24-bit BMP inside')
    offset = struct.unpack('<I', bmp[10:14])[0]
    w, h = struct.unpack('<ii', bmp[18:26])
    stride = (w * 3 + 3) & ~3
    rows = []
    for y in range(abs(h)):
        src = abs(h) - 1 - y if h > 0 else y  # bottom-up unless the height is negative
        line = bmp[offset + src * stride: offset + src * stride + w * 3]
        rows.append([(line[i + 2], line[i + 1], line[i]) for i in range(0, w * 3, 3)])
    fh = abs(h) // count
    return w, fh, [rows[i * fh:(i + 1) * fh] for i in range(count)]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('lkd')
    ap.add_argument('name')
    ap.add_argument('-o', '--out', required=True)
    args = ap.parse_args()

    w, h, clip = frames(args.lkd)
    shades = sorted({px for f in clip for row in f for px in row}, key=lambda c: 77 * c[0] + 150 * c[1] + 29 * c[2])
    if len(shades) > 4:
        raise SystemExit(f'{args.lkd}: {len(shades)} shades, expected at most 4')
    level = {c: i for i, c in enumerate(shades)}
    data = bytearray()
    for f in clip:
        flat = [level[px] for row in f for px in row]
        flat += [0] * (-len(flat) % 4)
        for i in range(0, len(flat), 4):
            data.append(flat[i] << 6 | flat[i + 1] << 4 | flat[i + 2] << 2 | flat[i + 3])

    name = args.name
    with open(args.out, 'w') as out:
        out.write(f'// Generated by tools/lkd2c.py from {args.lkd.rsplit("/", 1)[-1]} - do not edit.\n')
        out.write(f'// {len(clip)} frames of {w}x{h}, 2 bits a pixel, {len(data)} bytes.\n')
        out.write(f'// Shades as recorded, darkest first: {", ".join("#%02x%02x%02x" % c for c in shades)}\n')
        out.write('#pragma once\n#include <cstdint>\n\nnamespace adcore {\nnamespace pioneer_' + name + ' {\n\n')
        out.write(f'static const int W = {w}, H = {h}, FRAMES = {len(clip)};\n\n')
        out.write('static const uint8_t DATA[] = {\n')
        for i in range(0, len(data), 24):
            out.write('  ' + ', '.join(str(b) for b in data[i:i + 24]) + ',\n')
        out.write('};\n\n}  // namespace pioneer_' + name + '\n}  // namespace adcore\n')
    print(f'{args.out}: {len(clip)} frames {w}x{h}, {len(data)} bytes')


if __name__ == '__main__':
    main()
